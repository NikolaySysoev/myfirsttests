package api.dao.checks;

import api.configs.BackendVersion;

import java.util.function.Supplier;

/**
 * Гейт проверок на уровне БД: выполнять их или нет, решает версия бэкенда.
 * <p>
 * У легаси-версии внешнего хранилища нет физически, поэтому сверять API-ответ
 * с записью в базе там не с чем. При этом отключать целиком тесты, которые такую
 * сверку делают, нельзя — они проверяют ещё и API, и это покрытие нужно на обеих
 * версиях.
 * <p>
 * <b>Почему метод ровно один.</b> Здесь решается единственный вопрос — «есть ли у
 * версии БД», и он не зависит от количества сравниваемых моделей. Какие поля с
 * какими сверять, знает {@code dao-comparison.properties}, а он от версии не
 * зависит. Если бы этот интерфейс имел метод на каждую пару DTO/DAO, стоимость
 * стала бы произведением «модели × версии»: сто моделей означали бы сто пустых
 * заглушек в реализации без БД. Разделение осей оставляет здесь один метод
 * навсегда.
 */
public interface DbChecks {

    /**
     * Реализация, соответствующая версии. Единственный switch по наличию хранилища.
     */
    static DbChecks of(BackendVersion version) {
        return version.hasDatabase()
                ? new DatabaseChecks()
                : new NoDatabaseChecks(version);
    }

    /**
     * Сверяет модель, полученную из API, с записью в БД.
     * <p>
     * Запись передаётся {@link Supplier}'ом намеренно: на версии без хранилища он
     * не вызывается вовсе, поэтому лишнего соединения не открывается и попытки
     * читать чужую базу не происходит.
     *
     * @param apiModel    то, что вернуло API
     * @param daoSupplier ленивое получение записи из БД
     */
    void assertMatches(Object apiModel, Supplier<Object> daoSupplier);
}
